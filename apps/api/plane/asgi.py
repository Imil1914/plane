import os

os.environ.setdefault("DJANGO_SETTINGS_MODULE", "plane.settings.production")

from channels.auth import AuthMiddlewareStack
from channels.routing import ProtocolTypeRouter, URLRouter
from channels.security.websocket import AllowedHostsOriginValidator
from django.core.asgi import get_asgi_application

django_asgi_app = get_asgi_application()

# Import routes only after Django has populated the app registry. Consumers use
# project models during module import, so moving this import higher breaks ASGI startup.
from plane.ppm_canvas.routing import websocket_urlpatterns  # noqa: E402

application = ProtocolTypeRouter(
    {
        "http": django_asgi_app,
        "websocket": AllowedHostsOriginValidator(AuthMiddlewareStack(URLRouter(websocket_urlpatterns))),
    }
)
