/**
 * PPM branding is enabled by default for PPM builds. Set
 * PPM_BRAND_ENABLED=0 to restore the untouched Plane presentation.
 */
export function isPpmBrandEnabled(value: string | undefined): boolean {
  if (value === undefined || value.trim() === "") return true;
  return !DISABLED_FLAG_VALUES.has(value.trim().toLowerCase());
}

/**
 * The PPM shell can be rolled back independently, and is always disabled when
 * the PPM brand itself is disabled.
 */
export function isPpmShellEnabled(value: string | undefined, brandValue?: string): boolean {
  return isPpmBrandEnabled(brandValue) && isPpmBrandEnabled(value);
}

export function resolvePpmInitialLanguage(storedLanguage: string | null, shellEnabled: boolean): string {
  const persistedLanguage = storedLanguage?.trim();
  if (persistedLanguage) return persistedLanguage;
  return shellEnabled ? PPM_DEFAULT_LANGUAGE : "en";
}

export function shouldInitializePpmProfileLanguage({
  isOnboarded,
  profileLanguage,
  shellEnabled,
  storedLanguage,
}: {
  isOnboarded: boolean;
  profileLanguage: string | undefined;
  shellEnabled: boolean;
  storedLanguage: string | null;
}): boolean {
  return shellEnabled && !isOnboarded && profileLanguage === "en" && storedLanguage === PPM_DEFAULT_LANGUAGE;
}

export function resolvePpmLocale(language: string | undefined): TPpmLocale {
  return language?.toLowerCase().startsWith("ru") ? "ru" : "en";
}

export function getPpmTranslation(language: string | undefined, key: TPpmTranslationKey): string {
  return PPM_TRANSLATIONS[resolvePpmLocale(language)][key];
}

export function getPpmProjectPath(workspaceSlug: string, projectId: string, route: TPpmProjectRoute): string {
  return `/${workspaceSlug}/projects/${projectId}/${PPM_PROJECT_ROUTE_SEGMENTS[route]}`;
}
